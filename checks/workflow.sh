#!/usr/bin/env bash
# checks/workflow.sh — the deterministic steps of the workflow; checks/workflow.mk
# orders them. Each exits non-zero when its step fails, and says how to fix it.
#
#   workflow.sh hooks [<dir>]      the hooks this checkout needs are installed
#                                  in <dir> (default: the repository's hooks
#                                  dir): prek's shims for pre-commit, commit-msg
#                                  and pre-push, and git-issue's pre-push hook as
#                                  pre-push.legacy, which prek runs after its own
#   workflow.sh rows [<row>...]    run each row (default: checks/affected.sh's)
#                                  through run.sh with LW_ATTEST=0; prints
#                                  `<row> <exit> <seconds>s` and exits 1 if any is not 0.
#                                  Each row's output is kept as <row>.log in
#                                  $LW_ROW_LOGS (default: a new directory under
#                                  $LW_STATE/rows, else $TMPDIR/rows), a `/` in
#                                  a row id written `_`; a failing row's log
#                                  path goes to stderr
#   workflow.sh baseline [<row>...]  the same rows on $LW_STATE_BASE (default
#                                  origin/main) with this tree's checks/ laid
#                                  over it, in a throwaway worktree: a new
#                                  check must fail there; exits 0 either way;
#                                  its logs go to a sibling directory, -base
#   workflow.sh pushed [<remote>]  every local issue note is on <remote>
#                                  (default origin); exits 1 naming the
#                                  unpushed ones
#   workflow.sh pr-ready <title> <body-file>  the title is a Conventional
#                                  Commit subject and the body passes
#                                  comment-lint, before `gh pr create/edit`
#   workflow.sh ci <pr>            the PR's checks, asked once: 0 all passed,
#                                  1 one failed, 3 still running (ask again
#                                  later; never a polling loop)
#   workflow.sh                    self-test
set -uo pipefail
cd "$(dirname "$0")/.."

hooks() {
  local dir=${1:-$(git rev-parse --git-common-dir)/hooks} h fail=0
  for h in pre-commit commit-msg pre-push; do
    if ! [ -x "$dir/$h" ] || ! grep -q 'generated by prek' "$dir/$h"; then
      echo "hooks: $h is not prek's shim; run: prek install" >&2; fail=1
    fi
  done
  if ! [ -x "$dir/pre-push.legacy" ] || ! grep -q 'Installed by: git issue setup-sync' "$dir/pre-push.legacy"; then
    if grep -qs 'Installed by: git issue setup-sync' "$dir/pre-push.backup"; then
      echo "hooks: git-issue's pre-push hook is missing (prek install -f drops it); run: cp $dir/pre-push.backup $dir/pre-push.legacy" >&2
    else
      echo "hooks: git-issue's pre-push hook is missing; run: git issue setup-sync enable, then prek install" >&2
    fi
    fail=1
  fi
  return $fail
}

row_logs() {   # <suffix>: the directory a run's row logs go to, made, as an absolute path
  local d=${LW_ROW_LOGS:-${LW_STATE:-${TMPDIR:-/tmp}}/rows/$(date +%Y%m%d-%H%M%S)-$$}
  d=${d%/}$1
  mkdir -p "$d" && (cd "$d" && pwd) || { echo "rows: cannot make the log directory $d" >&2; return 2; }
}

run_rows() {   # <tree> <logs> <row>...: run each row in <tree>, print `<row> <exit> <seconds>s`, keep its output as <logs>/<row>.log; exit 1 if any failed
  local tree=$1 logs=$2 id rc log start fail=0; shift 2
  for id in "$@"; do
    log=$logs/${id//\//_}.log
    start=$SECONDS
    (cd "$tree" && LW_ATTEST=0 checks/run.sh "$id" >"$log" 2>&1); rc=$?
    printf '%s %s %ss\n' "$id" "$rc" "$((SECONDS - start))"
    [ $rc = 0 ] || { fail=1; echo "rows: $id exited $rc; log: $log" >&2; }
  done
  return $fail
}

rows() {
  [ $# -gt 0 ] || set -- $(checks/affected.sh)
  [ $# -gt 0 ] || { echo "rows: no row reads a changed file" >&2; return 0; }
  local logs; logs=$(row_logs "") || return 2
  run_rows . "$logs" "$@"
}

baseline() {
  local base=${LW_STATE_BASE:-origin/main} wt
  [ $# -gt 0 ] || set -- $(checks/affected.sh)
  [ $# -gt 0 ] || { echo "baseline: no row reads a changed file" >&2; return 0; }
  wt=$(mktemp -d) && git worktree add -q --detach "$wt" "$base" || return 2
  trap "git worktree remove --force '$wt' 2>/dev/null; rm -rf '$wt'" RETURN
  rm -rf "$wt/checks" && cp -R checks "$wt/checks"
  local logs; logs=$(row_logs -base) || return 2
  run_rows "$wt" "$logs" "$@"
  return 0
}

pushed() {
  local remote=${1:-origin} remote_refs ref sha theirs fail=0
  remote_refs=$(git ls-remote "$remote" 'refs/notes/issue-*') || { echo "pushed: cannot reach $remote" >&2; return 2; }
  while read -r sha ref; do
    theirs=$(awk -v r="$ref" '$2==r{print $1}' <<<"$remote_refs")
    [ "$theirs" = "$sha" ] && continue
    if [ -n "$theirs" ] && git cat-file -e "$theirs" 2>/dev/null && git merge-base --is-ancestor "$sha" "$theirs"; then
      continue   # the remote is ahead: someone else's edit, fetched by the next sync
    fi
    echo "pushed: ${ref#refs/notes/} is not on $remote; run: .git/hooks/pre-push.legacy $remote <url> </dev/null" >&2; fail=1
  done < <(git for-each-ref --format='%(objectname) %(refname)' 'refs/notes/issue-*')
  return $fail
}

pr_ready() {
  local title=${1:?title} body=${2:?body file} fail=0
  checks/subject-lint.py --title "$title" || fail=1
  checks/comment-lint.py "$body" || fail=1
  return $fail
}

ci() {
  local pr=${1:?pr number} rc
  ${GH:-gh} pr checks "$pr"; rc=$?
  case $rc in
    0) return 0 ;;
    8) echo "ci: #$pr still running" >&2; return 3 ;;
    *) return 1 ;;
  esac
}

selftest() {
  local t fail=0 out rc
  t=$(mktemp -d) && trap "rm -rf '$t'" EXIT
  check() { if eval "$2"; then echo "ok   $1"; else echo "FAIL $1"; fail=1; fi; }
  mkdir -p "$t/hooks"
  for h in pre-commit commit-msg pre-push; do printf '#!/bin/sh\n# File generated by prek\n' > "$t/hooks/$h"; done
  printf '#!/bin/sh\n# Installed by: git issue setup-sync\n' > "$t/hooks/pre-push.backup"
  chmod +x "$t"/hooks/*
  out=$(hooks "$t/hooks" 2>&1); rc=$?
  check 'a missing git-issue hook fails and names the backup' '[ $rc = 1 ] && grep -q "cp .*pre-push.backup" <<<"$out"'
  printf '#!/bin/sh\n# some other hook\n' > "$t/hooks/pre-push.legacy"; chmod +x "$t/hooks/pre-push.legacy"
  check 'a legacy hook that is not git-issue'"'"'s fails' '! hooks "$t/hooks" 2>/dev/null'
  cp "$t/hooks/pre-push.backup" "$t/hooks/pre-push.legacy"
  check 'all hooks present passes' 'hooks "$t/hooks" 2>/dev/null'
  printf '#!/bin/sh\n# a hand-written hook\n' > "$t/hooks/commit-msg"
  check 'a hook that is not the shim fails' '! hooks "$t/hooks" 2>/dev/null'

  git init -q --bare "$t/remote.git" && git init -q "$t/repo" && cd "$t/repo" || return 1
  git -c user.name=t -c user.email=t@t commit -q --allow-empty -m init
  git remote add origin "$t/remote.git"
  git -c user.name=t -c user.email=t@t notes --ref=refs/notes/issue-aaaaaaa add -m one HEAD
  check 'an unpushed issue note fails' '! pushed 2>/dev/null'
  git push -q origin refs/notes/issue-aaaaaaa 2>/dev/null
  check 'a pushed issue note passes' 'pushed'
  git -c user.name=t -c user.email=t@t notes --ref=refs/notes/issue-aaaaaaa append -m two HEAD
  out=$(pushed 2>&1); rc=$?
  check 'a local edit not pushed fails and names the issue' '[ $rc = 1 ] && grep -q issue-aaaaaaa <<<"$out"'
  git push -q origin refs/notes/issue-aaaaaaa 2>/dev/null
  git update-ref refs/notes/issue-aaaaaaa "$(git rev-parse refs/notes/issue-aaaaaaa^)"
  check 'a remote ahead of the local copy passes' 'pushed'
  cd - >/dev/null

  printf '#!/bin/sh\nexit $FAKE_RC\n' > "$t/gh" && chmod +x "$t/gh"
  local gh_rc want
  for c in '0 0' '1 1' '8 3'; do
    read -r gh_rc want <<<"$c"
    FAKE_RC=$gh_rc GH=$t/gh ci 1 >/dev/null 2>&1; rc=$?
    check "ci maps gh's exit $gh_rc to $want" '[ $rc = $want ]'
  done
  mkdir -p "$t/tree/checks"
  printf '#!/bin/sh\necho "ran $1"; [ "$1" = good ]\n' > "$t/tree/checks/run.sh" && chmod +x "$t/tree/checks/run.sh"
  mkdir -p "$t/logs"
  out=$(run_rows "$t/tree" "$t/logs" good bad 2>"$t/rows.err"); rc=$?
  check 'rows prints each row and its exit, and fails on one failure' '[ $rc = 1 ] && [ "$(cut -d" " -f1,2 <<<"$out")" = "$(printf "good 0\nbad 1")" ]'
  check 'rows prints each row'"'"'s seconds' '! grep -vqE "^[^ ]+ [0-9]+ [0-9]+s$" <<<"$out"'
  check 'rows keeps every row'"'"'s output' 'grep -qx "ran good" "$t/logs/good.log" && grep -qx "ran bad" "$t/logs/bad.log"'
  check 'rows names the failing row'"'"'s log on stderr' 'grep -q "bad exited 1; log: $t/logs/bad.log" "$t/rows.err" && ! grep -q "good exited" "$t/rows.err"'
  out=$(run_rows "$t/tree" "$t/logs" good/x 2>/dev/null)
  check 'a row id with / keeps its log' '[ "${out% *}" = "good/x 1" ] && grep -qx "ran good/x" "$t/logs/good_x.log"'
  out=$(cd "$t" && LW_ROW_LOGS=rel/logs/ row_logs -base)
  check 'row_logs makes a relative LW_ROW_LOGS absolute, the suffix on the name' '[ "$out" = "$(cd "$t" && pwd)/rel/logs-base" ] && [ -d "$t/rel/logs-base" ]'
  check 'row_logs fails when it cannot make the directory' '! LW_ROW_LOGS=/dev/null/x row_logs "" 2>/dev/null'
  printf 'Fixed by #58. P6.0 passes on its head.\n' > "$t/body.md"
  check 'pr-ready passes a good title and body' 'pr_ready "fix(driver): read programs in user" "$t/body.md" >/dev/null'
  check 'pr-ready fails a title that is not a Conventional Commit' '! pr_ready "driver: read programs" "$t/body.md" >/dev/null'
  printf 'Fixed by #58.\n\nGenerated with a tool\n' > "$t/bad.md"
  check 'pr-ready fails a body with a footer' '! pr_ready "fix(driver): read programs in user" "$t/bad.md" >/dev/null'
  return $fail
}

case ${1:-} in
  hooks)    shift; hooks "$@" ;;
  rows)     shift; . checks/env.sh; rows "$@" ;;
  baseline) shift; . checks/env.sh; baseline "$@" ;;
  pushed)   shift; pushed "$@" ;;
  pr-ready) shift; pr_ready "$@" ;;
  ci)       shift; ci "$@" ;;
  '')       selftest ;;
  *)        echo "usage: workflow.sh hooks|rows|baseline|pushed|pr-ready|ci" >&2; exit 2 ;;
esac
